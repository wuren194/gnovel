"""Generate the browser's pacing policy from the canonical registry accessor."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.core.project import TOOLBOX_ROOT, world_render_policy

OUTPUT = TOOLBOX_ROOT / "dashboard/js/world-render-policy.js"


def render_policy_module() -> str:
    payload = json.dumps(world_render_policy(), ensure_ascii=False, indent=2)
    return ("// Generated by scripts/sync_world_render_policy.py; edit shared/registries/world-render.json.\n"
            f"export const WORLD_RENDER_POLICY = Object.freeze({payload});\n")


def main() -> None:
    argparse.ArgumentParser(description=__doc__).parse_args()
    OUTPUT.write_text(render_policy_module(), encoding="utf-8")


if __name__ == "__main__":
    main()
