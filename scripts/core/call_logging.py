"""Local diagnostic copies of calls, never project state or approval evidence.

Only transport boundaries create records. Observers inside a transport can add
already-read inputs without following any path supplied by a caller.
"""
from __future__ import annotations

from contextlib import contextmanager, redirect_stderr, redirect_stdout
from contextvars import ContextVar
from datetime import datetime, timezone
import os
from pathlib import Path
import sys
import time
import uuid

from .call_log_metadata import correlations, target_context, toolbox_identity
from .call_log_redaction import credential_values, json_bytes, sanitize
from .call_log_store import CallLogStore
from .project import call_logging_policy
from .structure_store import StructureError

_ACTIVE: ContextVar[CallRecorder | None] = ContextVar("govel_call_log", default=None)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def log_root() -> Path:
    value = os.environ.get("GOVEL_LOG_DIR")
    return Path(os.path.abspath(os.path.expanduser(value))) if value else Path.home() / "Library/Logs/govel"


def _settings(policy: dict, store: CallLogStore) -> tuple[str, str]:
    override = os.environ.get("GOVEL_LOG_MODE")
    if override is not None:
        mode, source = override, "environment"
    else:
        config = store.read_config()
        if config is None:
            mode, source = policy["defaultMode"], "registry"
        else:
            if not isinstance(config, dict) or set(config) != {"schemaVersion", "mode"} or type(config["schemaVersion"]) is not int or config["schemaVersion"] != 1:
                raise ValueError("invalid call logging configuration")
            mode, source = config["mode"], "user_config"
    if not isinstance(mode, str) or mode not in {"off", "summary", "full"}:
        raise ValueError("invalid call logging mode")
    return mode, source


def _unavailable() -> None:
    # Never render an exception, path, argument or payload in this fallback.
    # Writing to the original stderr also keeps this notice out of the captured
    # business output. A closed stderr must not replace a completed operation.
    try:
        stream = getattr(sys.stderr, "_call_log_target", sys.stderr)
        stream.write("CALL_LOG_UNAVAILABLE: 本地调用日志不可用；原调用结果与退出码不变。\n")
        stream.flush()
    except Exception:
        pass


def exception_details(exc) -> dict:
    try:
        return {"type": type(exc).__name__, "code": getattr(exc, "code", None),
                "message": str(exc), "details": getattr(exc, "details", None)}
    except Exception:
        return {"type": type(exc).__name__, "detailsUnavailable": True}


def _metadata(data: dict, policy: dict, payloads: dict, stage: str, known_values=()) -> dict:
    copied = sanitize(data, policy)
    full = copied["value"]
    # Values generated by the logger (success/full/etc.) are not echoes of a
    # user's password that happens to equal one of those words.
    for field in ("name", "target", "client", "correlations"):
        if field in full:
            full[field] = sanitize(full[field], policy, known_values=known_values)["value"]
    if len(json_bytes(full)) <= policy["maxMetadataBytes"]:
        return full
    # Huge correlation lists and self-reported client fields follow the same
    # full/summary/size policy as content, rather than bypassing payload limits.
    name = stage + "Metadata"
    payloads[name] = copied
    result = {"metadataCapture": "payload", "metadataPayload": name}
    priority = ("entrypoint", "name", "startedAt", "endedAt", "pid", "status", "outcome", "exitCode",
                "durationMs", "delivery", "mode", "modeSource", "target", "client", "toolbox",
                "timingScope", "byteUnit", "fileReferences")
    for key in priority:
        if key in full and len(json_bytes({**result, key: full[key]})) <= policy["maxMetadataBytes"]:
            result[key] = full[key]
    return result


class CallRecorder:
    def __init__(self):
        self.enabled = False
        self.finished = False
        self.payloads = {}
        self.target = {}
        self.policy = {}
        self.metadata = {}
        self.failure_reported = False
        self.known_values = set()

    def unavailable(self):
        if not self.failure_reported:
            _unavailable()
            self.failure_reported = True

    def observe(self, name: str, value, *, omitted: str | None = None, byte_length: int | None = None):
        if not self.enabled:
            return
        try:
            self.known_values.update(credential_values(value, self.policy))
            copied = sanitize(value, self.policy, known_values=self.known_values)
            if omitted:
                copied.update(complete=False, originalBytes=byte_length)
                copied["issues"] = [*copied.get("issues", []), omitted]
            self.payloads[name] = copied
            if name in {"arguments", "machineArguments", "effectiveArguments"}:
                self.target.update(target_context(copied["value"]))
        except Exception:
            self.unavailable()
            self.payloads[name] = {"value": None, "originalBytes": byte_length, "redactions": 0,
                                   "complete": False, "issues": ["CAPTURE_UNAVAILABLE"]}

    def set_name(self, value: str):
        if self.enabled:
            try:
                self.metadata["name"] = sanitize(value, self.policy, known_values=self.known_values)["value"]
            except Exception:
                self.unavailable()

    def finish(self, *, status="success", outcome="success", exit_code=None, error=None, delivery="not_observed"):
        if not self.enabled or self.finished:
            return
        self.finished = True
        try:
            elapsed = time.monotonic() - self.started_clock
            references = []
            for name, copied in self.payloads.items():
                if name not in {"stdout", "stderr"}:
                    references.extend(correlations(copied["value"], name, self.policy["maxDepth"]))
            metadata = {**self.metadata, "status": status, "outcome": outcome,
                        "endedAt": _now(), "durationMs": elapsed * 1000,
                        "target": self.target, "correlations": references, "delivery": delivery,
                        "toolbox": toolbox_identity()}
            if exit_code is not None:
                metadata["exitCode"] = exit_code
            if error is not None:
                self.observe("exception", error)
            # Metadata can also contain user-provided names and correlation
            # values. It follows the same before-persistence redaction path.
            metadata = _metadata(metadata, self.policy, self.payloads, "finish", self.known_values)
            self.store.finish(self.call_id, metadata, self.payloads, self.mode)
        except Exception:
            self.unavailable()


def _begin(entrypoint: str, request, name: str, client, enabled: bool) -> CallRecorder:
    recorder = CallRecorder()
    # A deliberate off switch does not create files or require healthy local
    # logging configuration. It never affects a business validation gate.
    if not enabled or os.environ.get("GOVEL_LOG_MODE") == "off":
        return recorder
    try:
        policy = call_logging_policy()
        store = CallLogStore(log_root(), policy)
        mode, source = _settings(policy, store)
        if mode == "off":
            return recorder
        recorder.known_values = credential_values({"request": request, "client": client}, policy)
        copied = sanitize(request, policy, known_values=recorder.known_values)
        recorder.call_id = "CL-" + uuid.uuid4().hex
        recorder.target = target_context(copied["value"])
        metadata = {
            "entrypoint": entrypoint, "name": name, "startedAt": _now(), "pid": os.getpid(),
            "mode": mode, "modeSource": source, "client": client or {"trust": "unknown", "info": None},
            "target": recorder.target, "toolbox": toolbox_identity(),
            "timingScope": "entry_execution_excluding_start_and_finish_persistence",
            "byteUnit": "serialized_utf8_bytes_not_model_tokens",
            "fileReferences": "paths_only_unless_content_was_observed",
        }
        initial = {"request": copied}
        recorder.metadata = sanitize(metadata, policy)["value"]
        start_metadata = _metadata(recorder.metadata, policy, initial, "start", recorder.known_values)
        store.start(recorder.call_id, start_metadata, initial, mode)
        recorder.store, recorder.policy, recorder.mode = store, policy, mode
        recorder.started_clock = time.monotonic()
        recorder.enabled = True
    except Exception:
        recorder.unavailable()
    return recorder


@contextmanager
def call_scope(entrypoint: str, request, *, name: str, client=None, enabled=True):
    parent = _ACTIVE.get()
    if parent is not None:
        # Direct adapters remain one invocation. There is no second CLI event
        # when MCP dispatches through novelctl._dispatch.
        yield parent
        return
    recorder = _begin(entrypoint, request, name, client, enabled)
    token = _ACTIVE.set(recorder)
    try:
        yield recorder
    except BaseException as exc:
        if isinstance(exc, SystemExit):
            code = exc.code if isinstance(exc.code, int) else 0 if exc.code is None else 1
            recorder.finish(status="success" if code == 0 else "error",
                            outcome="success" if code == 0 else "argument_error", exit_code=code)
        else:
            recorder.finish(status="error", outcome="interrupted" if isinstance(exc, KeyboardInterrupt) else "exception",
                            error=exception_details(exc))
        raise
    else:
        recorder.finish()
    finally:
        _ACTIVE.reset(token)


def observe_payload(name: str, value) -> None:
    recorder = _ACTIVE.get()
    if recorder is not None:
        recorder.observe(name, value)


def observe_arguments(arguments: dict, *, effective=False) -> None:
    recorder = _ACTIVE.get()
    if recorder is None:
        return
    recorder.observe("effectiveArguments" if effective else "arguments",
                     {key: value for key, value in arguments.items() if key != "operation_examples"})
    if not effective:
        binding = arguments.get("operation_binding")
        if isinstance(binding, str):
            recorder.set_name(binding)
        else:
            names = [arguments.get("group"), arguments.get("action")]
            action = arguments.get("action")
            if isinstance(action, str):
                names.append(arguments.get(action + "_action"))
            recorder.set_name(" ".join(value for value in names if isinstance(value, str)))


def observe_file_input(label: str, path, content) -> None:
    """Called after a business reader succeeds; never opens or resolves path."""
    recorder = _ACTIVE.get()
    if recorder is not None and recorder.enabled:
        previous = recorder.payloads.get("fileInputs", {}).get("value", [])
        previous = previous if isinstance(previous, list) else []
        recorder.observe("fileInputs", [*previous, {"label": label, "inputPath": str(path), "content": content,
                                                   "contentCaptured": True, "origin": "business_reader"}])


class _CaptureStream:
    def __init__(self, target, limit):
        self._call_log_target = target
        self.limit, self.byte_length, self.chunks = limit, 0, []
        self.omitted = False

    def write(self, text):
        result = self._call_log_target.write(text)
        self.byte_length += len(text.encode("utf-8", errors="surrogatepass"))
        if self.byte_length > self.limit:
            self.chunks.clear()
            self.omitted = True
        elif not self.omitted:
            self.chunks.append(text)
        return result

    def writelines(self, lines):
        for line in lines:
            self.write(line)

    def flush(self):
        return self._call_log_target.flush()

    def __getattr__(self, name):
        return getattr(self._call_log_target, name)


@contextmanager
def capture_cli_streams(recorder):
    if not recorder.enabled:
        yield
        return
    stdout = _CaptureStream(sys.stdout, recorder.policy["maxPayloadBytes"])
    stderr = _CaptureStream(sys.stderr, recorder.policy["maxPayloadBytes"])
    try:
        with redirect_stdout(stdout), redirect_stderr(stderr):
            yield
    finally:
        for name, capture in (("stdout", stdout), ("stderr", stderr)):
            recorder.observe(name, "".join(capture.chunks) if not capture.omitted else None,
                             omitted="STREAM_CAPTURE_LIMIT_EXCEEDED" if capture.omitted else None,
                             byte_length=capture.byte_length)


def response_outcome(response, *, mcp=False) -> tuple[str, str]:
    if response is None:
        return "success", "notification" if mcp else "success"
    payload = response
    if mcp and isinstance(response, dict):
        if "error" in response:
            return "error", "protocol_error"
        result = response.get("result", {})
        if isinstance(result, dict):
            payload = result.get("structuredContent", result)
            if result.get("isError") is True:
                code = payload.get("code") if isinstance(payload, dict) else None
                return "error", "argument_error" if code in {"ARGUMENTS_INVALID", "TOOL_NOT_FOUND"} else "business_error"
    if isinstance(payload, dict) and (payload.get("ok") is False or payload.get("error")):
        return "error", "argument_error" if payload.get("code") == "ARGUMENTS_INVALID" else "business_error"
    return "success", "success"


def _query_store():
    try:
        policy = call_logging_policy()
        return policy, CallLogStore(log_root(), policy)
    except Exception as exc:
        raise StructureError("CALL_LOG_UNAVAILABLE", "本地调用日志配置或目录不可用") from exc


def logging_status() -> dict:
    try:
        policy, store = _query_store()
        mode, source = _settings(policy, store)
        return {"ok": True, "code": "CALL_LOG_STATUS", "available": True, "mode": mode,
                "modeSource": source, "directory": str(store.root), "policy": policy, "storage": store.stats(),
                "coverage": ["novelctl.main", "mcp_server.handle", "mcp_stdio_parse_errors"],
                "excluded": ["log_management", "direct_python_and_dashboard_calls", "client_chat_and_model_api"],
                "trust": "diagnostic_copy_not_project_state_or_approval"}
    except Exception:
        return {"ok": False, "code": "CALL_LOG_UNAVAILABLE", "available": False,
                "error": "本地调用日志配置或目录不可用；业务调用不受日志故障阻断。"}


def configure_logging(mode: str) -> dict:
    if mode not in {"off", "summary", "full"}:
        raise StructureError("ARGUMENTS_INVALID", "mode must be off, summary or full")
    policy, store = _query_store()
    try:
        store.write_config({"schemaVersion": 1, "mode": mode})
    except Exception as exc:
        raise StructureError("CALL_LOG_UNAVAILABLE", "无法保存本地调用日志开关") from exc
    return {**logging_status(), "code": "CALL_LOG_CONFIGURED", "configuredMode": mode}


def _time_filter(value: str | None, field: str):
    if value is None:
        return None
    try:
        if not isinstance(value, str):
            raise ValueError("string required")
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            raise ValueError("timezone required")
        return parsed
    except (TypeError, ValueError) as exc:
        raise StructureError("ARGUMENTS_INVALID", field + " must be an ISO timestamp with a timezone") from exc


def list_call_logs(*, project=None, task=None, chapter=None, since=None, until=None,
                   status=None, entrypoint=None, limit=None, offset=None) -> dict:
    policy, store = _query_store()
    limit = policy["defaultQueryLimit"] if limit is None else limit
    offset = 0 if offset is None else offset
    if (type(limit) is not int or not 1 <= limit <= policy["maxQueryLimit"]
            or type(offset) is not int or offset < 0):
        raise StructureError("ARGUMENTS_INVALID", "invalid call log pagination")
    after, before = _time_filter(since, "since"), _time_filter(until, "until")
    if after and before and after > before:
        raise StructureError("ARGUMENTS_INVALID", "since must not be after until")
    if status is not None and status not in {"success", "error", "incomplete"}:
        raise StructureError("ARGUMENTS_INVALID", "invalid call status")
    project = os.path.abspath(os.path.expanduser(project)) if project is not None else None
    try:
        result = store.list_calls()
    except Exception as exc:
        raise StructureError("CALL_LOG_UNAVAILABLE", "无法读取本地调用列表") from exc
    selected = []
    issues = list(result.get("issues", []))
    for row in result["calls"]:
        metadata = row.get("metadata", row)
        target = metadata.get("target", {})
        if (not isinstance(target, dict) or not isinstance(metadata.get("startedAt"), str)
                or not isinstance(row.get("status"), str)
                or row["status"] not in {"success", "error", "incomplete"}):
            issues.append({"callId": row["callId"], "code": "LOG_METADATA_INVALID", "excludedFromResults": True})
            continue
        if any(expected is not None and target.get(key) != expected
               for key, expected in (("projectRoot", project), ("task", task), ("chapterId", chapter))):
            continue
        if status is not None and row.get("status", metadata.get("status")) != status:
            continue
        if entrypoint is not None and metadata.get("entrypoint") != entrypoint:
            continue
        try:
            started = _time_filter(metadata.get("startedAt"), "startedAt")
        except StructureError:
            issues.append({"callId": row["callId"], "code": "LOG_START_TIME_INVALID", "excludedFromResults": True})
            continue
        if (after or before) and (started is None or (after and started < after) or (before and started > before)):
            continue
        selected.append(row)
    selected.sort(key=lambda row: (row.get("metadata", row).get("startedAt", ""), row["callId"]), reverse=True)
    page = selected[offset:offset + limit]
    return {"ok": True, "code": "CALL_LOG_LIST", "calls": page, "total": len(selected),
            "offset": offset, "limit": limit, "hasMore": offset + len(page) < len(selected),
            "issues": issues, "untrustedData": True}


def show_call_log(callId: str) -> dict:
    _, store = _query_store()
    try:
        return {"ok": True, "code": "CALL_LOG_DETAIL", **store.show(callId), "untrustedData": True}
    except Exception as exc:
        raise StructureError("CALL_LOG_UNAVAILABLE", "调用记录不存在、损坏或无法读取") from exc


def prune_call_logs() -> dict:
    _, store = _query_store()
    try:
        return {"ok": True, "code": "CALL_LOG_PRUNED", **store.prune()}
    except Exception as exc:
        raise StructureError("CALL_LOG_UNAVAILABLE", "无法清理本地调用日志") from exc
