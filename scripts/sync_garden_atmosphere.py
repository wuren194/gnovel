"""Generate the browser garden profile from its canonical registry accessor."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.core.project import TOOLBOX_ROOT, garden_atmosphere_policy

OUTPUT = TOOLBOX_ROOT / "dashboard/js/garden-atmosphere-policy.js"


def render_atmosphere_module() -> str:
    payload = json.dumps(garden_atmosphere_policy(), ensure_ascii=False, indent=2)
    return ("// Generated by scripts/sync_garden_atmosphere.py; edit shared/registries/garden-atmosphere.json.\n"
            f"export const GARDEN_ATMOSPHERE = Object.freeze({payload});\n")


def main() -> None:
    argparse.ArgumentParser(description=__doc__).parse_args()
    OUTPUT.write_text(render_atmosphere_module(), encoding="utf-8")


if __name__ == "__main__":
    main()
